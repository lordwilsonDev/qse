"""Generating a decision artifact that actually runs.

The generated module is not a description of a solution and not a stub: it is a
complete, stdlib-only Python program that reads rows, applies a threshold rule,
and prints one JSON object. It is written to be executed by
``qse/build/executor.py`` in a temporary directory, and attacked by
``qse/verification/adversary.py`` afterwards.

The rule is derived from usable **measured** evidence when there is any, and
otherwise falls back to a conservative rule whose ``basis`` says in plain words
that nobody has measured it. That distinction is carried inside the artifact, so
an unvalidated rule cannot later be mistaken for a validated one.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping, Sequence
from dataclasses import replace

from ..core.artifact import Artifact, make_artifact
from ..core.evidence import Evidence
from ..ids import slug
from .specification import BuildSpec, outcome_columns

__all__ = ["BEACON", "FALLBACK_THRESHOLD", "default_rule", "render", "generate"]

BEACON = "# generated by qse.build.generator -- do not edit by hand"

#: Hours. Used only when nothing was measured, and always labelled as such.
FALLBACK_THRESHOLD = 24.0
VALID_OPS = (">=", "<=")
_STRENGTH_ORDER = {"STRONG": 0, "MODERATE": 1, "WEAK": 2}


def _parse_rule_text(text: str) -> dict | None:
    """Read ``"field >= 24"`` back out of a runner that reported a rule string."""
    parts = str(text).split()
    if len(parts) != 3 or parts[1] not in VALID_OPS:
        return None
    try:
        threshold = float(parts[2])
    except ValueError:
        return None
    return {"field": parts[0], "op": parts[1], "threshold": threshold}


def _doc_line(text: object) -> str:
    """One safe docstring line from arbitrary text.

    Evidence methods and boundaries are free text and end up inside the generated
    module's docstring. A stray newline or triple quote there would produce a
    module that does not parse, so free text is flattened and de-quoted before it
    is interpolated. The literal assignments below use ``repr`` and need none of
    this.
    """
    return (
        str(text)
        .replace("\\", "/")
        .replace('"""', "'''")
        .replace("\r", " ")
        .replace("\n", " ")
        .strip()
    )


def _median(values: Sequence[float]) -> float | None:
    ordered = sorted(values)
    if not ordered:
        return None
    middle = len(ordered) // 2
    if len(ordered) % 2:
        return ordered[middle]
    return (ordered[middle - 1] + ordered[middle]) / 2


def default_rule(spec: BuildSpec, evidence: Iterable[Evidence] = ()) -> dict:
    """A threshold rule, preferring one that was actually measured.

    Order of preference: a rule a runner reported verbatim; a field and threshold
    a runner observed; then a conservative fallback that names itself unvalidated.
    """
    ranked = sorted(
        (
            item
            for item in evidence
            if isinstance(item, Evidence)
            and item.usable()
            and isinstance(item.observed, Mapping)
        ),
        key=lambda item: (_STRENGTH_ORDER.get(item.strength, 3), item.eid),
    )
    # A measured rule is only usable if it does not read the outcome to predict the
    # outcome; a circular rule is skipped here exactly as an unmeasured one is.
    outcomes = set(outcome_columns(evidence))

    for item in ranked:
        observed = item.observed
        parsed = _parse_rule_text(str(observed.get("rule", "")))
        if parsed and parsed.get("field") not in outcomes:
            return {
                **parsed,
                "action": "escalate",
                "basis": f"rule reported by {item.method} over {item.source} (evidence {item.eid})",
                "validated": item.kind in ("MEASURED", "REPRODUCED"),
            }
        field = observed.get("field") or observed.get("precursor")
        threshold = observed.get("threshold")
        if (isinstance(field, str) and field and field not in outcomes
                and isinstance(threshold, (int, float))):
            op = observed.get("op")
            return {
                "field": field,
                "op": op if op in VALID_OPS else ">=",
                "threshold": float(threshold),
                "action": str(observed.get("action", "escalate")),
                "basis": f"threshold observed by {item.method} over {item.source} (evidence {item.eid})",
                "validated": True,
            }

    numbers: list[float] = []
    for item in ranked:
        if isinstance(item.observed, Mapping):
            values = item.observed.get("values")
            if isinstance(values, Sequence) and not isinstance(values, (str, bytes)):
                numbers.extend(float(v) for v in values if isinstance(v, (int, float)))
    # No measured field exists, so there is nothing the run is entitled to flag on.
    # The honest artifact is an explicit detector-less one: it names no field, says
    # why, and flags nothing. Inventing a field from the input list would be a rule
    # chosen by construction rather than by measurement -- and could win the control
    # arm by alphabetical luck, which is not evidence that questioning worked.
    threshold = _median(numbers)
    return {
        "field": None,
        "detector": False,
        "op": ">=",
        "threshold": round(threshold, 4) if threshold is not None else FALLBACK_THRESHOLD,
        "action": "escalate",
        "basis": (
            "unvalidated: no usable measured evidence exists, so this artifact carries no "
            "detector -- there is no field the run is entitled to flag on, and inventing "
            "one would be a rule chosen by construction rather than by measurement"
        ),
        "validated": False,
    }


def render(spec: BuildSpec, *, rule: Mapping) -> str:
    """The artifact's source text. Deterministic in the spec and the rule."""
    operation = rule.get("op", ">=")
    if operation not in VALID_OPS:
        raise ValueError(f"rule op must be one of {VALID_OPS}, got {operation!r}")
    field = rule.get("field")
    detector = bool(rule.get("detector", field is not None))
    baked = {
        "field": (str(field) if field else None),
        "op": operation,
        "threshold": float(rule.get("threshold", FALLBACK_THRESHOLD)),
        "action": str(rule.get("action", "escalate")),
        "basis": str(rule.get("basis", "unspecified")),
        "validated": bool(rule.get("validated", False)),
        "detector": detector,
    }
    rule_line = (f"{baked['field']} {baked['op']} {baked['threshold']} -> {baked['action']}"
                 if detector else "(no detector: this artifact names no field)")

    header = [
        BEACON,
        f'"""Generated decision artifact for {_doc_line(spec.hypothesis)}.',
        "",
        f"Title:    {_doc_line(spec.title)}",
        f"Spec:     {_doc_line(spec.sid)}",
        f"Rule:     {_doc_line(rule_line)}",
        f"Basis:    {_doc_line(baked['basis'])}",
        f"Detector: {baked['detector']}",
        f"Validated: {baked['validated']}",
        "",
        "Reads a JSON list of rows from argv[1], or from stdin when no path is given,",
        "and prints one JSON object to stdout. Standard library only, no network, no",
        "clock: the same rows always produce the same output.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "import json",
        "import sys",
        "",
        f"SPEC_ID = {spec.sid!r}",
        f"TITLE = {spec.title!r}",
        f"HYPOTHESIS = {spec.hypothesis!r}",
        f"RULE = {baked!r}",
        f"SECTIONS = {list(spec.sections)!r}",
        f"ACCEPTANCE = {list(spec.acceptance)!r}",
    ]
    body = [
        "",
        "",
        "def decide(row):",
        '    """Apply the rule to one row. Returns why, not only whether."""',
        "    if not isinstance(row, dict):",
        '        raise TypeError("a row must be an object")',
        '    if RULE["field"] is None:',
        '        return {"flag": False, "action": "none", "value": None,',
        '                "reason": "no detector: this artifact carries no measured field"}',
        '    raw = row.get(RULE["field"])',
        "    if raw is None:",
        '        return {"flag": False, "action": "none", "value": None,',
        '                "reason": "field %r absent from the row" % (RULE["field"],)}',
        "    try:",
        "        value = float(raw)",
        "    except (TypeError, ValueError):",
        '        return {"flag": False, "action": "none", "value": raw,',
        '                "reason": "value %r is not numeric" % (raw,)}',
        '    hit = value >= RULE["threshold"] if RULE["op"] == ">=" else value <= RULE["threshold"]',
        "    if not hit:",
        '        return {"flag": False, "action": "none", "value": value, "reason": ""}',
        '    return {"flag": True, "action": RULE["action"], "value": value,',
        '            "reason": "%s %s %s" % (value, RULE["op"], RULE["threshold"])}',
        "",
        "",
        "def main(argv):",
        '    if len(argv) > 1 and argv[1] != "-":',
        '        with open(argv[1], "r", encoding="utf-8") as handle:',
        "            rows = json.load(handle)",
        "    else:",
        "        rows = json.load(sys.stdin)",
        "    if not isinstance(rows, list):",
        '        raise SystemExit("expected a JSON list of rows")',
        "    decisions = [decide(row) for row in rows]",
        '    payload = {"spec": SPEC_ID, "module": TITLE, "rule": RULE,',
        '               "rows": len(rows), "flagged": sum(1 for d in decisions if d["flag"]),',
        '               "decisions": decisions}',
        "    json.dump(payload, sys.stdout, sort_keys=True)",
        '    sys.stdout.write("\\n")',
        "    return 0",
        "",
        "",
        'if __name__ == "__main__":',
        "    raise SystemExit(main(sys.argv))",
    ]
    return "\n".join(header + body) + "\n"


def generate(
    spec: BuildSpec,
    *,
    builder: str,
    rule: Mapping | None = None,
) -> Artifact:
    """Build the artifact. Without a rule or evidence the rule is conservative and
    says so inside itself; callers with measured evidence should pass
    ``default_rule(spec, evidence)`` explicitly."""
    if not str(builder).strip():
        raise ValueError("an artifact needs a named builder")
    chosen = dict(rule) if rule is not None else default_rule(spec, ())
    content = render(spec, rule=chosen)
    artifact = make_artifact(
        hypothesis=spec.hypothesis,
        kind=spec.artifact_kind,
        title=spec.title,
        builder=builder,
        content=content,
        path=None,
        reproduce=f"python3 {(slug(spec.title) or 'artifact')}.py <rows.json>",
        requires=spec.inputs,
    )
    return replace(artifact, state="CONSTRUCTED")
